import { createRequire } from 'node:module';
const require = createRequire(`${process.env.CLOUD_UI_DIR ?? `${process.env.HOME}/code/cloud-ui/dev-palette`}/package.json`);
const { chromium } = require('@playwright/test');
const here = new URL('.', import.meta.url).pathname;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 2 });
await page.goto(`file://${here}splash.html`);
await page.waitForTimeout(300);
await page.screenshot({ path: `${here}command-palette-splash.png` });
await browser.close();
